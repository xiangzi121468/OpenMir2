-- 
-- SELECT Id, Name, Reference 
-- FROM stditems 
-- WHERE Reference IS NOT NULL 
--   AND Reference != '' 
--   AND Reference LIKE '%effect%';
-- 
-- ========================================
-- 特效预留范围
-- ========================================
-- 100-109: 冰霜/水系
-- 110-119: 火焰系
-- 120-129: 雷电系
-- 130-139: 暗影/毒系
-- 140-149: 神圣/光系
-- 150-159: 自然/大地系
-- 160-169: 风系
-- 170-249: 扩展预留
-- 
-- ========================================
-- 添加新武器特效示例
-- ========================================
-- 
-- 1. 在数据库中设置特效类型:
--    UPDATE stditems SET Reference = '{"effect":120}' WHERE Name = '雷霆之锤';
-- 
-- 2. 准备特效图片 (20帧PNG):
--    weapon_effect_120_00.png ~ weapon_effect_120_19.png
-- 
-- 3. 使用打包工具生成 .data 文件:
--    python tools/pack_to_data.py --input effects/ --output ShineEffect.data --start-index 400
-- 
-- 4. 将生成的 .data 文件复制到客户端 Data 目录
